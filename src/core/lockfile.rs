use serde::{Deserialize, Serialize};
use std::error::Error;
use std::fs;
use std::path::{Path, PathBuf};
use std::time::{SystemTime, UNIX_EPOCH};

#[derive(Debug, Serialize, Deserialize, PartialEq, Clone)]
pub struct JoltLock {
    pub version: u32,
    #[serde(rename = "package", default)]
    pub packages: Vec<LockedPackage>,
}

#[derive(Debug, Serialize, Deserialize, PartialEq, Clone)]
pub struct LockedPackage {
    pub name: String,
    pub version: String,
    pub checksum: String,
    #[serde(default)]
    pub dependencies: Vec<String>,
}

impl Default for JoltLock {
    fn default() -> Self {
        Self::new()
    }
}

impl JoltLock {
    pub fn new() -> Self {
        Self {
            version: 1,
            packages: Vec::new(),
        }
    }

    pub fn load_from_file(path: &Path) -> Result<Self, Box<dyn Error + Send + Sync>> {
        let content = fs::read_to_string(path)?;
        let lock: JoltLock = toml::from_str(&content)?;
        Ok(lock)
    }

    pub fn validate_manifest_dependencies(
        &self,
        manifest: &crate::core::JoltManifest,
    ) -> Result<(), String> {
        for dependencies in [&manifest.dependencies, &manifest.dev_dependencies] {
            let Some(dependencies) = dependencies else {
                continue;
            };

            for (name, spec) in dependencies {
                let (version, local_path) = crate::core::JoltManifest::parse_dependency_spec(spec);
                if local_path.is_some() {
                    continue;
                }

                let version =
                    version.ok_or_else(|| format!("La dependencia '{}' no tiene versión", name))?;
                let parts: Vec<&str> = name.split(':').collect();
                if parts.len() != 2 || parts.iter().any(|part| part.is_empty()) {
                    return Err(format!(
                        "Dependencia inválida '{}'; usa groupId:artifactId",
                        name
                    ));
                }

                let Some(locked) = self.packages.iter().find(|pkg| pkg.name == *name) else {
                    return Err(format!(
                        "La dependencia '{}'@'{}' no está en jolt.lock; regenera el lockfile",
                        name, version
                    ));
                };
                if locked.version != version {
                    return Err(format!(
                        "La dependencia '{}' requiere '{}', pero jolt.lock contiene '{}'; regenera el lockfile",
                        name, version, locked.version
                    ));
                }
            }
        }

        Ok(())
    }

    pub fn save_to_file(&self, path: &Path) -> Result<(), Box<dyn Error + Send + Sync>> {
        let toml_str = toml::to_string_pretty(self)?;
        let header = "# This file is automatically @generated by Jolt.\n# It is not intended for manual editing.\n\n";
        let content = format!("{}{}", header, toml_str);
        let parent = path.parent().unwrap_or_else(|| Path::new("."));
        fs::create_dir_all(parent)?;
        let temp_path = temporary_path(path)?;
        fs::write(&temp_path, content)?;

        if let Err(rename_error) = fs::rename(&temp_path, path) {
            let backup_path = temporary_path(path)?;
            if let Err(backup_error) = fs::rename(path, &backup_path) {
                let _ = fs::remove_file(&temp_path);
                return Err(format!(
                    "No se pudo reemplazar '{}' ni crear respaldo: {}",
                    path.display(),
                    backup_error
                )
                .into());
            }

            if let Err(replace_error) = fs::rename(&temp_path, path) {
                let _ = fs::rename(&backup_path, path);
                let _ = fs::remove_file(&temp_path);
                return Err(format!(
                    "No se pudo publicar '{}' ({}; intento inicial: {})",
                    path.display(),
                    replace_error,
                    rename_error
                )
                .into());
            }
            let _ = fs::remove_file(backup_path);
        }
        Ok(())
    }

    pub fn add_or_update_package(&mut self, pkg: LockedPackage) {
        if let Some(pos) = self.packages.iter().position(|p| p.name == pkg.name) {
            self.packages[pos] = pkg;
        } else {
            self.packages.push(pkg);
        }
        self.packages.sort_by(|a, b| a.name.cmp(&b.name));
    }

    pub fn remove_package(&mut self, name: &str) -> bool {
        let initial_len = self.packages.len();
        self.packages.retain(|p| p.name != name);
        self.packages.len() < initial_len
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_lockfile_serialization() {
        let mut lock = JoltLock::new();
        lock.add_or_update_package(LockedPackage {
            name: "com.google.code.gson:gson".to_string(),
            version: "2.14.0".to_string(),
            checksum: "sha256:abcd1234".to_string(),
            dependencies: vec![],
        });

        let toml_str = toml::to_string(&lock).unwrap();
        let parsed: JoltLock = toml::from_str(&toml_str).unwrap();
        assert_eq!(parsed.packages.len(), 1);
        assert_eq!(parsed.packages[0].name, "com.google.code.gson:gson");
    }

    #[test]
    fn rejects_manifest_dependency_with_different_locked_version() {
        let manifest = crate::core::JoltManifest::parse(
            r#"
                [dependencies]
                "com.example:library" = "2.0.0:linux"
            "#,
        )
        .unwrap();
        let mut lock = JoltLock::new();
        lock.add_or_update_package(LockedPackage {
            name: "com.example:library".to_string(),
            version: "1.0.0:linux".to_string(),
            checksum: "sha256:abcd".to_string(),
            dependencies: vec![],
        });

        let error = lock.validate_manifest_dependencies(&manifest).unwrap_err();

        assert!(error.contains("com.example:library"));
        assert!(error.contains("2.0.0:linux"));
        assert!(error.contains("1.0.0:linux"));
    }

    #[test]
    fn accepts_manifest_dependency_with_matching_locked_version() {
        let manifest = crate::core::JoltManifest::parse(
            r#"
                [dependencies]
                "com.example:library" = "2.0.0:linux"
            "#,
        )
        .unwrap();
        let mut lock = JoltLock::new();
        lock.add_or_update_package(LockedPackage {
            name: "com.example:library".to_string(),
            version: "2.0.0:linux".to_string(),
            checksum: "sha256:abcd".to_string(),
            dependencies: vec![],
        });

        assert!(lock.validate_manifest_dependencies(&manifest).is_ok());
    }

    #[test]
    fn save_replaces_lockfile_without_leaving_temporary_files() {
        let temp_dir = std::env::temp_dir().join("jolt_test_lockfile_atomic");
        let _ = fs::remove_dir_all(&temp_dir);
        fs::create_dir_all(&temp_dir).unwrap();
        let path = temp_dir.join("jolt.lock");

        let mut first = JoltLock::new();
        first.add_or_update_package(LockedPackage {
            name: "com.example:library".to_string(),
            version: "1.0.0".to_string(),
            checksum: "sha256:first".to_string(),
            dependencies: vec![],
        });
        first.save_to_file(&path).unwrap();

        let mut second = JoltLock::new();
        second.add_or_update_package(LockedPackage {
            name: "com.example:library".to_string(),
            version: "2.0.0".to_string(),
            checksum: "sha256:second".to_string(),
            dependencies: vec![],
        });
        second.save_to_file(&path).unwrap();

        let saved = JoltLock::load_from_file(&path).unwrap();
        assert_eq!(saved.packages[0].version, "2.0.0");
        assert_eq!(
            fs::read_dir(&temp_dir)
                .unwrap()
                .filter_map(Result::ok)
                .filter(|entry| entry.file_name().to_string_lossy().contains(".tmp-"))
                .count(),
            0
        );

        let _ = fs::remove_dir_all(&temp_dir);
    }
}

fn temporary_path(path: &Path) -> Result<PathBuf, Box<dyn Error + Send + Sync>> {
    let timestamp = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_err(|e| format!("Reloj del sistema inválido: {}", e))?
        .as_nanos();
    let file_name = path
        .file_name()
        .ok_or_else(|| format!("Ruta de lockfile inválida: {}", path.display()))?
        .to_string_lossy();
    Ok(path.with_file_name(format!(
        ".{}.tmp-{}-{}",
        file_name,
        std::process::id(),
        timestamp
    )))
}
